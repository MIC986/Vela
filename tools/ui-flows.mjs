// Exercises state transitions a person would hit, asserting on what's on screen.
export default async ({ eval: ev, key, shot, wait, mouse, type, console: problems }) => {
  const ok = (label, value) => console.log(`${value ? 'PASS' : 'FAIL'}  ${label}`);
  await wait(2500);
  const focusedHome = () => ev('document.querySelector("#home .tile.focused")?.dataset.index');
  const tab = () => ev('document.body.dataset.tab');
  const layerCount = () => ev('document.getElementById("overlays").children.length');

  ok('home has focus on first tile', (await focusedHome()) === '0');
  await key('Left');
  ok('left at start stays put', (await focusedHome()) === '0');
  await key('Right', 40, 40);
  await wait(500);
  const end = await focusedHome();
  const count = await ev('document.querySelectorAll("#home .tile").length');
  ok(`right stops on last tile (${end} of ${count})`, +end === count - 1);
  ok('last tile is All games', await ev('document.querySelector("#home .tile.focused").classList.contains("more")'));
  await shot('10-home-end');
  await key('Enter');
  await wait(800);
  ok('All games tile opens Library', (await tab()) === 'library');
  await key('q');
  await wait(500);
  ok('Q returns Home', (await tab()) === 'home');
  await key('Left', 40, 30);
  await wait(400);
  await key('Up');
  ok('up reaches the top bar', await ev('document.getElementById("topbar").classList.contains("nav-focus")'));
  ok('home tile lost focus', (await focusedHome()) === undefined);
  await key('Right', 4);
  await wait(200);
  await key('Enter');
  await wait(700);
  ok('settings opens from the top bar', await ev('!!document.querySelector(".settings")'));
  await shot('11-settings');
  await key('Down', 4, 200);
  await wait(300);
  await key('Right');
  await wait(300);
  await shot('12-settings-playing');
  await key('Enter');
  await wait(600);
  await shot('13-settings-select');
  await key('Esc');
  await wait(400);
  await key('Esc');
  await wait(200);
  for (let i = 0; i < 2; i += 1) { await key('Down'); await wait(260); }
  await shot('14-settings-display');
  await wait(600);
  await key('Down', 3, 260);
  await wait(800);
  await shot('15-settings-storage');
  await key('Esc');
  await wait(600);
  ok('settings closed', (await layerCount()) === 0);
  await key('Down');
  await wait(300);

  // Library filters.
  const barKey = () => ev('document.querySelector(".lib-bar [data-key].focused")?.dataset.key');
  const toChip = async (wanted) => {
    const keys = await ev('[...document.querySelectorAll(".lib-bar [data-key]")].map((n) => n.dataset.key)');
    const from = keys.indexOf(await barKey());
    const to = keys.indexOf(wanted);
    await key(to > from ? 'Right' : 'Left', Math.abs(to - from), 120);
  };
  await key('e');
  await wait(800);
  const total = await ev('document.querySelector(".lib-count").textContent');
  await key('Up');
  await wait(200);
  ok('library up reaches filter bar', (await barKey()) !== undefined);
  await toChip('status:installed');
  await key('Enter');
  await wait(700);
  const installed = await ev('document.querySelector(".lib-count").textContent');
  ok(`Installed filter narrows ${total} to ${installed}`, parseInt(installed) < parseInt(total.replace(/,/g, '')));
  await shot('16-library-installed');
  await toChip('sort');
  await key('Enter');
  await wait(700);
  await shot('17-library-sort');
  ok('sort sheet open', (await layerCount()) === 1);
  await key('Down');
  await key('Enter');
  await wait(800);
  const first = await ev('document.querySelector(".grid .tile .t-caption").textContent');
  console.log('first after A-Z', first);
  await toChip('status:all');
  await key('Enter');
  await wait(600);
  await key('Down');
  await wait(400);
  ok('down from bar enters grid', await ev('!!document.querySelector(".grid .tile.focused")'));

  // Paging and virtualization.
  await key('PageDown', 6, 180);
  await wait(900);
  const live = await ev('[...document.querySelectorAll(".grid .tile")].filter(t => t.style.visibility !== "hidden").length');
  console.log('live tiles', live);
  await shot('18-library-deep');
  let ups = 0;
  while (!(await barKey()) && ups < 60) {
    await key('Up', 1, 50);
    ups += 1;
  }
  ok(`all the way up reaches bar (${ups})`, ups < 60);

  // Search with no results, and a real one.
  await key('/');
  await wait(500);
  ok('search input is focused', await ev('document.activeElement?.tagName === "INPUT"'));
  await type('zzzzqq');
  await wait(500);
  ok('nonsense search shows none', (await ev('document.querySelector(".search-count").textContent')).startsWith('0'));
  ok('an empty search says so', await ev('document.querySelector(".search-empty").classList.contains("on")'));
  await ev('(() => { const i = document.querySelector(".search input"); i.value = "cyber"; i.dispatchEvent(new Event("input")); })()');
  await wait(500);
  await key('Down');
  await wait(300);
  await key('Enter');
  await wait(1500);
  ok('search result opens its page', await ev('!!document.querySelector(".gp")'));
  await shot('19-game-from-search');
  await key('Esc');
  await wait(500);
  await key('Esc');
  await wait(500);
  ok('everything closed', (await layerCount()) === 0);
  await key('q');
  await wait(500);

  // Mouse.
  await mouse(300, 760);
  await wait(400);
  ok('hover focuses a tile', (await focusedHome()) !== undefined);
  const clickOn = async (selector) => {
    const [x, y] = await ev(`(() => { const r = document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect(); return [r.x + r.width / 2, r.y + r.height / 2]; })()`);
    await mouse(x, y, true);
    await wait(700);
  };
  await clickOn('[data-do=search]');
  ok('clicking the search icon opens search', await ev('!!document.querySelector(".search")'));
  await key('Esc');
  await wait(500);
  await clickOn('[data-do=settings]');
  ok('clicking the gear opens settings', await ev('!!document.querySelector(".settings")'));
  await clickOn('.set-tab:nth-of-type(2)');
  ok('clicking a settings section switches to it', (await ev('document.querySelector(".set-track h2").textContent')) === 'Appearance');
  await wait(500);
  const [sx, sy, sw] = await ev('(() => { const r = [...document.querySelectorAll(".slider")].at(-1).getBoundingClientRect(); return [r.left, r.top + r.height / 2, r.width]; })()');
  await mouse(sx + sw * 0.25, sy, true);
  await wait(300);
  ok('a slider follows the mouse', (await ev('[...document.querySelectorAll(".num")].at(-1).textContent')) === '40%');
  await key('Esc');
  await wait(300);
  await key('Esc');
  await wait(500);
  ok('escape closes settings after mouse use', !(await ev('!!document.querySelector(".settings")')));
  await clickOn('.tab[data-tab=library]');
  ok('clicking the Library tab switches', (await ev('document.body.dataset.tab')) === 'library');
  const [tx, ty] = await ev('(() => { const r = document.querySelector(".grid .tile .t-card").getBoundingClientRect(); return [r.x + r.width / 2, r.y + r.height / 2]; })()');
  await mouse(tx + 1, ty);
  await wait(300);
  await clickOn('.grid .tile.focused');
  await wait(900);
  ok('clicking a library tile opens its page', await ev('!!document.querySelector(".gp")'));
  ok('with a mouse the page only offers Back', (await ev('[...document.querySelectorAll(".gp-hints .hint")].map((h) => h.textContent).join()')).endsWith('Back'));
  await clickOn('.gp .btn.round:last-child');
  ok('clicking the more button opens options', await ev('!!document.querySelector(".sheet")'));
  const menuRow = await ev('[...document.querySelectorAll(".sheet .mi")].findIndex((m) => m.textContent === "Customize") + 1');
  await clickOn(`.sheet .mi:nth-of-type(${menuRow})`);
  await wait(600);
  ok('options lead to Customize', (await ev('document.querySelector(".sheet h2").textContent')) === 'Customize');
  ok('customize can refresh artwork', await ev('[...document.querySelectorAll(".mi")].some((m) => m.textContent === "Refresh artwork")'));
  await key('Esc');
  await wait(500);
  await key('Esc');
  await wait(200);
  ok('closing flies the poster back to its tile', await ev('!!document.querySelector(".flip")'));
  await wait(700);
  ok('the tile is back after the flight', await ev('!document.querySelector(".flip") && [...document.querySelectorAll(".t-card")].every((c) => c.style.visibility !== "hidden")'));
  await clickOn('.tab[data-tab=home]');
  ok('clicking the Home tab switches', (await ev('document.body.dataset.tab')) === 'home');
  const full = await ev('document.body.classList.contains("fullscreen")');
  await clickOn('[data-do=fullscreen]');
  // Full screen comes in with its intro, and can't be left halfway through it.
  await wait(2800);
  await shot('23-fullscreen');
  ok('the full screen button toggles', (await ev('document.body.classList.contains("fullscreen")')) !== full);
  await key('F11');
  await wait(1400);
  ok('F11 toggles back', (await ev('document.body.classList.contains("fullscreen")')) === full);
  await wait(400);
  await clickOn('[data-win=max]');
  await wait(600);
  ok('maximize button works', await ev('window.__TAURI__.window.getCurrentWindow().isMaximized()'));
  await clickOn('[data-win=max]');
  await wait(600);
  ok('maximize button restores', !(await ev('window.__TAURI__.window.getCurrentWindow().isMaximized()')));

  console.log('layers', await layerCount(), 'problems', problems.length);
};
